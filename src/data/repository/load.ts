import type { ArtifactIntegrity, RuntimeGameData, GameDataManifest } from './contracts';
import { createGameDataRepository } from './repository';
import type { GameDataRepository } from './repository';
import { requireIntegrity } from './integrity';

/** One JSON parse per artifact; normalization and raw-source I/O never run here. */
export async function decodeArtifact(bytes: Uint8Array<ArrayBuffer>, expected: ArtifactIntegrity): Promise<unknown> {
  requireIntegrity(bytes.byteLength === expected.bytes, expected.file, 'generated byte length mismatch; regenerate data');
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
  const sha256 = Array.from(digest, b => b.toString(16).padStart(2, '0')).join('');
  requireIntegrity(sha256 === expected.sha256, expected.file, 'generated SHA-256 mismatch; regenerate data');
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
  const json = await new Response(stream).arrayBuffer();
  requireIntegrity(json.byteLength === expected.jsonBytes, expected.file, 'generated JSON length mismatch');
  return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(json)) as unknown;
}
let pending: Promise<GameDataRepository> | undefined;
/** Call only when game data is needed. Vite emits compressed assets, not raw imports. */
export function loadGameDataRepository(): Promise<GameDataRepository> {
  pending ??= (async () => {
    const [manifestModule, progression, abilities, itemsTreasure] = await Promise.all([
      import('../../generated/game-data/manifest.json?raw'),
      import('../../generated/game-data/progression.json.gz?url'),
      import('../../generated/game-data/abilities.json.gz?url'),
      import('../../generated/game-data/itemsTreasure.json.gz?url'),
    ]);
    const manifest = JSON.parse(manifestModule.default) as GameDataManifest;
    requireIntegrity(manifest.schemaVersion === 1 && manifest.generatorVersion === 1 && manifest.normalizationSchemaVersion === 1,
      'manifest', 'unsupported generated schema');
    const urls = { progression, abilities, itemsTreasure };
    const entries = await Promise.all((['progression', 'abilities', 'itemsTreasure'] as const).map(async name => {
      const response = await fetch(urls[name].default);
      requireIntegrity(response.ok, name, `cannot load generated artifact (HTTP ${response.status})`);
      // The on-disk contract is checked by generation and verified by byte hash here.
      // This is a transport boundary, not a second normalization implementation.
      return [name, await decodeArtifact(new Uint8Array(await response.arrayBuffer()), manifest.artifacts[name])] as const;
    }));
    return createGameDataRepository(Object.fromEntries(entries) as RuntimeGameData, manifest);
  })().catch(error => { pending = undefined; throw error; });
  return pending;
}
